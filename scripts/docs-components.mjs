const HEAD = `# Components

Every shared component, hook and one-home file, one line each. **Look here before building anything: if it's here, use it or extend it; never build a second thing that does the same job.** The file is the detail.

Generated by \`pnpm docs:components\` from the \`/** @panki … */\` line at the top of each file; change that line, never this file. A new shared piece gets its line in the same change; \`pnpm docs:check\` fails while this file is out of date.

Also one home each, though not listed: every colour is a token in \`apps/web/src/theme.css\`; the app's styles and its one phone breakpoint are \`apps/web/src/app.css\`; the extension's own looks are \`apps/extension/src/ui/extension.css\`; the fonts are self-hosted in \`apps/web/public/fonts/\`. What the browser must never draw by itself, and what draws it instead: \`docs/conventions/in-app-text.md\`.
`;

const posix = (path) => path.split(sep).join("/");
const isSource = (name) => /\.tsx?$/.test(name) && !/\.(d|test)\.tsx?$/.test(name);

function sourcesIn(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourcesIn(path);
    return isSource(name) ? [path] : [];
  });
}

/** The doc as the code says it, and what's wrong with the code's lines. */
export function componentsDoc() {
  const problems = [];
  const sections = SECTIONS.map((section) => {
    const base = join(root, section.base);
    const skipped = new Set((section.skip ?? []).map((file) => join(base, file)));
    const paths = new Set();
    for (const dir of section.roots) for (const path of sourcesIn(join(base, dir))) if (!skipped.has(path)) paths.add(path);
    for (const file of section.files) {
      const path = join(base, file);
      if (!existsSync(path)) problems.push(`${posix(relative(root, path))}: listed in scripts/docs-components.mjs, but isn't there`);
      else paths.add(path);
    }
    const rows = [...paths]
      .map((path) => {
        const shown = posix(relative(base, path));
        const first = readFileSync(path, "utf8").split(/\r?\n/, 1)[0];
        const where = posix(relative(root, path));
        const m = HEADER.exec(first);
        if (!m) {
          problems.push(`${where}: no \`/** @panki … */\` line at the top`);
          return null;
        }
        if (first.length > LINE_MAX) problems.push(`${where}: its @panki line is ${first.length} characters, over ${LINE_MAX}`);
        return { name: basename(shown).replace(/\.tsx?$/, ""), shown, says: m[1].replace(/\|/g, "\\|") };
      })
      .filter(Boolean)
      .sort((a, b) => (a.shown < b.shown ? -1 : a.shown > b.shown ? 1 : 0));
    return { ...section, rows };
  });

  const out = [HEAD];
  for (const { title, about, base, rows } of sections) {
    out.push(`## ${title}`, "");
    out.push(`${about ? `${about} ` : ""}Paths from \`${base}/\`.`, "");
    out.push("| Name | File | For |", "| --- | --- | --- |");
    for (const { name, shown, says } of rows) out.push(`| ${name} | \`${shown}\` | ${says} |`);
    out.push("");
  }
  return { text: out.join("\n"), problems, rows: sections.reduce((n, s) => n + s.rows.length, 0) };
}

/** Whether docs/COMPONENTS.md is what the code says, the problems named when it isn't. */
export function componentsCheck() {
  const { text, problems } = componentsDoc();
  const path = join(root, OUT);
  if (!existsSync(path) || readFileSync(path, "utf8") !== text) problems.push(`${OUT} is out of date: run \`pnpm docs:components\``);
  return problems;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const check = process.argv.includes("--check");
  const { text, problems, rows } = componentsDoc();
  if (check) {
    const all = componentsCheck();
    for (const problem of all) console.log(`FAIL: ${problem}`);
    if (!all.length) console.log(`${OUT} is up to date (${rows} rows).`);
    process.exit(all.length ? 1 : 0);
  }
  if (problems.length) {
    for (const problem of problems) console.log(`FAIL: ${problem}`);
    process.exit(1);
  }
  writeFileSync(join(root, OUT), text);
  console.log(`Wrote ${OUT}: ${rows} rows, ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB.`);
}
