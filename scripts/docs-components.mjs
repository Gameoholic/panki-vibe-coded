// Writes docs/COMPONENTS.md from the one line at the top of each shared piece:
//
//   /** @panki What to reach for it for. What never to hand-roll instead. */
//
// The code is the registry; the doc is generated from it, so it can't drift. Every .ts/.tsx file under a section's
// roots must carry the line, as must every file the section lists by name. `--check` writes nothing and fails when
// the doc on disk isn't what the code says (`pnpm docs:check` runs it).
